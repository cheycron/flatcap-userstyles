#!/usr/bin/env python3
"""Generate the Flatcap 2.0 token block of the UserStyles.

    python3 scripts/build.py              # rewrite the generated blocks in styles/*.user.less and README.md
    python3 scripts/build.py --check      # fail if a block is stale, a hex colour sits outside it, metadata drifts, or contrast misses a target
    python3 scripts/build.py --sync       # refresh src/theme.json from ../00-Flatcap, then rebuild
    python3 scripts/build.py --contrast   # print the full contrast report

Input  : src/theme.json, a versioned copy of the Flatcap 2.0 core (the only source of values).
Output : the text between `flatcap:tokens:begin/end` in every styles/*.user.less (LESS mixins .fc-tokens-slate() and
         .fc-tokens-daylight()), and the blocks between <!-- build:NAME --> markers in README.md.

Colours are assigned by role inside each style; this script never maps by palette position and no hex value is
written by hand outside the generated block. Python 3.10+, standard library only. Output is deterministic.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "src" / "theme.json"
CORE = (ROOT / ".." / "00-Flatcap").resolve()
STYLES = sorted((ROOT / "styles").glob("*.user.less"))
README = ROOT / "README.md"
MODES = ("slate", "daylight")
BEGIN = "/* flatcap:tokens:begin"
END = "/* flatcap:tokens:end */"
SCHEME = {"slate": "dark", "daylight": "light"}

# Roles of the core that the UserStyles do not use (increased-contrast overrides are not wired into the sites).
SKIP_PREFIX = ("contrast.",)

# (foreground, background, minimum, where). Thresholds follow the Flatcap accessibility contract:
# primary text 7:1, informative text 5:1, labels 4.5:1, functional boundaries and focus 3:1.
PAIRS = [
    ("text.primary", "bg.canvas", 7, "body text on page canvas"),
    ("text.primary", "bg.surface", 7, "text on panels and sidebars"),
    ("text.primary", "bg.raised", 7, "text on menus, dialogs and fields"),
    ("text.primary", "bg.hover", 7, "text on hovered rows"),
    ("text.primary", "bg.selected", 7, "text on selected rows"),
    ("text.secondary", "bg.canvas", 5, "secondary text on canvas"),
    ("text.secondary", "bg.surface", 5, "secondary text on panels"),
    ("text.secondary", "bg.raised", 5, "secondary text on menus"),
    ("text.muted", "bg.canvas", 5, "meta text on canvas"),
    ("text.muted", "bg.surface", 5, "meta text on panels"),
    ("accent.fg", "bg.canvas", 5, "links on canvas"),
    ("accent.fg", "bg.surface", 5, "links on panels"),
    ("accent.fg", "bg.raised", 5, "links on menus"),
    ("accent.on", "accent.fill", 4.5, "label on filled button"),
    ("accent.on", "accent.hover", 4.5, "label on hovered filled button"),
    ("selection.fg", "selection.bg", 4.5, "selected text"),
    ("border.control", "bg.canvas", 3, "control boundary on canvas"),
    ("border.control", "bg.surface", 3, "control boundary on panels"),
    ("focus.ring", "bg.canvas", 3, "focus ring on canvas"),
    ("focus.ring", "bg.surface", 3, "focus ring on panels"),
    ("danger.fg", "bg.canvas", 5, "error text"),
    ("success.fg", "bg.canvas", 5, "success text"),
    ("warning.fg", "bg.canvas", 5, "warning text"),
    ("data.4", "bg.canvas", 3, "upvote mark (Reddit)"),
]


def load() -> dict:
    return json.loads(THEME.read_text(encoding="utf-8"))


def lin(c: int) -> float:
    v = c / 255
    return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4


def lum(hexv: str) -> float:
    r, g, b = (int(hexv[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def ratio(a: str, b: str) -> float:
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def lessname(role: str) -> str:
    return role.replace(".", "-")


def roles(theme: dict, mode: str) -> list[tuple[str, str]]:
    return [(k, v) for k, v in theme["themes"][mode].items() if not k.startswith(SKIP_PREFIX)]


def tokens_block(theme: dict) -> str:
    ty, me = theme["typography"], theme["metrics"]
    out = [
        f"{BEGIN} (generated by scripts/build.py from src/theme.json {theme['version']}; do not edit by hand) */",
        f"@font-ui: ~'{ty['font.ui']}';",
        f"@font-dense: ~'{ty['font.dense']}';",
        f"@font-code: ~'{ty['font.code']}';",
        f"@radius-control: {me['radius.control']};",
        f"@focus-width: {me['focus.width']};",
        f"@focus-offset: {me['focus.offset']};",
    ]
    for mode in MODES:
        out.append(f".fc-tokens-{mode}() {{")
        out.append(f"  @color-scheme: {SCHEME[mode]};")
        for k, v in roles(theme, mode):
            out.append(f"  @{lessname(k)}: {v};")
        out.append(f"  @shadow-overlay: {theme['elevation'][mode]['shadow.overlay']};")
        out.append("}")
    out.append(END)
    return "\n".join(out)


def split_block(text: str) -> tuple[str, str, str]:
    i = text.index(BEGIN)
    j = text.index(END) + len(END)
    return text[:i], text[i:j], text[j:]


def used_roles(text: str) -> set[str]:
    _, _, after = split_block(text)
    return set(re.findall(r"@([a-z]+-[a-z0-9]+)(?![\w-])", after)) | set(re.findall(r"--fc-([a-z]+-[a-z0-9]+)", after))


def readme_blocks(theme: dict) -> dict[str, str]:
    usage: dict[str, list[str]] = {}
    for p in STYLES:
        site = p.name.removesuffix(".user.less")
        for r in used_roles(p.read_text(encoding="utf-8")):
            usage.setdefault(r, []).append(site)
    rows = ["| Role | Slate | Daylight | Used by |", "| :--- | :--- | :--- | :--- |"]
    for k in theme["themes"]["slate"]:
        n = lessname(k)
        if n in usage:
            s, d = theme["themes"]["slate"][k], theme["themes"]["daylight"][k]
            rows.append(f"| `{k}` | `{s}` | `{d}` | {', '.join(sorted(usage[n]))} |")
    meta = (
        f"Token source: `src/theme.json`, Flatcap core {theme['version']} (`{theme['name']}`, {theme['description']}). "
        f"Fonts: `font.ui` = {theme['typography']['font.ui']}; `font.dense` = {theme['typography']['font.dense']}; "
        f"`font.code` = {theme['typography']['font.code']}."
    )
    return {"roles": "\n".join(rows), "source": meta}


def sub_blocks(text: str, blocks: dict[str, str]) -> str:
    for name, body in blocks.items():
        pat = re.compile(rf"(<!-- build:{name} -->\n)(.*?)(\n<!-- /build:{name} -->)", re.S)
        if not pat.search(text):
            sys.exit(f"README.md is missing the <!-- build:{name} --> block")
        text = pat.sub(lambda m: m.group(1) + body + m.group(3), text)
    return text


def expected(theme: dict) -> dict[Path, str]:
    out = {}
    tb = tokens_block(theme)
    for p in STYLES:
        pre, _, post = split_block(p.read_text(encoding="utf-8"))
        out[p] = pre + tb + post
    return out


def contrast_rows(theme: dict):
    for mode in MODES:
        t = theme["themes"][mode]
        for fg, bg, need, where in PAIRS:
            r = ratio(t[fg], t[bg])
            yield mode, fg, bg, need, r, where


def hex_outside(text: str) -> list[str]:
    _, _, after = split_block(text)
    bad = []
    pre = text[:text.index(BEGIN)]
    for scope, chunk in (("header", pre), ("body", after)):
        for n, line in enumerate(chunk.splitlines(), 1):
            if scope == "header" and line.startswith("@"):
                continue
            # attribute selectors that match colours written by the sites themselves are not colours we author
            clean = re.sub(r'\[[^\]]*#[0-9a-fA-F]{3,8}[^\]]*\]', "", line)
            if re.search(r"(?<![\w&@/-])#[0-9a-fA-F]{3,8}\b", clean) and "%2F" not in clean:
                bad.append(f"{scope}:{n}: {line.strip()}")
    return bad


def meta_errors(text: str, theme: dict, name: str) -> list[str]:
    errs = []
    m = re.search(r"^@version\s+(\S+)", text, re.M)
    if not m or m.group(1) != theme["version"]:
        errs.append(f"{name}: @version is {m.group(1) if m else None}, core is {theme['version']}")
    for key in ("name", "namespace", "author", "homepageURL", "supportURL", "updateURL", "license"):
        if not re.search(rf"^@{key}\s+\S", text, re.M):
            errs.append(f"{name}: missing @{key}")
    for need in ("@preprocessor   less", '@var select mode', '@var checkbox webfonts'):
        if need not in text:
            errs.append(f"{name}: missing `{need}`")
    for fn in ("slate", "daylight"):
        if f".fc-tokens-{fn}();" not in text:
            errs.append(f"{name}: never applies .fc-tokens-{fn}()")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sync", action="store_true")
    ap.add_argument("--contrast", action="store_true")
    a = ap.parse_args()

    if a.sync:
        src = CORE / "src" / "theme.json"
        if not src.is_file():
            sys.exit(f"core not found: {src}")
        shutil.copyfile(src, THEME)
        print(f"synced {THEME.relative_to(ROOT)} from {src}")

    theme = load()
    if a.contrast:
        fails = 0
        for mode, fg, bg, need, r, where in contrast_rows(theme):
            ok = r >= need
            fails += not ok
            print(f"{'ok  ' if ok else 'FAIL'} {mode:8} {fg:15} on {bg:12} {r:5.2f}:1 (>= {need}) {where}")
        return 1 if fails else 0

    want = expected(theme)
    readme = README.read_text(encoding="utf-8") if README.exists() else ""
    rb = readme_blocks(theme)
    new_readme = sub_blocks(readme, rb) if readme else ""

    if a.check:
        errs = []
        for p, txt in want.items():
            cur = p.read_text(encoding="utf-8")
            if cur != txt:
                errs.append(f"{p.relative_to(ROOT)}: generated block is stale (run scripts/build.py)")
            errs += [f"{p.name}: hex outside generated block -> {b}" for b in hex_outside(cur)]
            errs += meta_errors(cur, theme, p.name)
        if readme and new_readme != readme:
            errs.append("README.md: generated blocks are stale (run scripts/build.py)")
        for mode, fg, bg, need, r, where in contrast_rows(theme):
            if r < need:
                errs.append(f"contrast {mode} {fg} on {bg}: {r:.2f} < {need} ({where})")
        if not STYLES:
            errs.append("no styles found")
        if errs:
            print("\n".join(errs))
            return 1
        print(f"ok: {len(STYLES)} styles, tokens {theme['version']}, generated blocks current, contrast targets met")
        return 0

    for p, txt in want.items():
        p.write_text(txt, encoding="utf-8")
    if readme:
        README.write_text(new_readme, encoding="utf-8")
    print(f"wrote {len(want)} styles" + (" and README.md" if readme else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
